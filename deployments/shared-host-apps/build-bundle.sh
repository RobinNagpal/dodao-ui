#!/usr/bin/env bash
# Assembles a Next.js app's standalone build into the directory the shared Lightsail host runs:
#
#   deployments/shared-host-apps/dist/<app>/
#   ├── index.js              ← what systemd runs: node /srv/<app>/current/index.js
#   ├── node_modules/         ← traced dependencies (pnpm symlinks preserved, all relative)
#   ├── shared/web-core/      ← traced workspace package
#   └── <app>/
#       ├── server.js         ← Next's standalone server
#       ├── .next/            ← server build + .next/static (copied in here)
#       └── public/           ← copied in here
#
# Run after `pnpm --filter <app> build` (which needs `output: 'standalone'` in its next.config).
# The deploy workflow rsyncs the result to /srv/<app>/next and swaps it into /srv/<app>/current.
#
#   bash deployments/shared-host-apps/build-bundle.sh academy-ui
set -euo pipefail

app="${1:?usage: build-bundle.sh <app>   (academy-ui | simulations)}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
standalone="$root/$app/.next/standalone"
out="$root/deployments/shared-host-apps/dist/$app"

# Ubuntu 24.04 on x86_64, which is what the host runs. An engine built for the wrong libc or
# OpenSSL fails at the first query, not at start-up — so check for it here instead.
engine_name="libquery_engine-debian-openssl-3.0.x.so.node"

if [[ ! -f "$standalone/$app/server.js" ]]; then
  echo "error: $standalone/$app/server.js not found — build $app first, with output: 'standalone'" >&2
  exit 1
fi

rm -rf "$out"
mkdir -p "$out"
cp -a "$standalone/." "$out/"

# `next build` leaves static assets and public/ out of the standalone tree on purpose; the
# server expects them beside server.js.
cp -a "$root/$app/.next/static" "$out/$app/.next/static"
if [[ -d "$root/$app/public" ]]; then
  cp -a "$root/$app/public" "$out/$app/public"
fi

# Never ship an env file: the host's /etc/<app>-api.env (written by the workflow) is the only
# source of runtime configuration.
find "$out" -maxdepth 2 -name '.env*' -type f -delete

if [[ -z "$(find "$out" -name "$engine_name" -print -quit)" ]]; then
  echo "error: $engine_name is not in the bundle — is it in $app/prisma/schema.prisma's binaryTargets?" >&2
  exit 1
fi

# rsync copies symlinks as symlinks, so one pointing outside the bundle would dangle on the host.
absolute_links="$(find "$out" -type l -lname '/*' -print)"
if [[ -n "$absolute_links" ]]; then
  echo "error: absolute symlinks in the bundle would dangle on the host:" >&2
  echo "$absolute_links" >&2
  exit 1
fi

cat >"$out/index.js" <<INDEX
// Generated by deployments/shared-host-apps/build-bundle.sh — the entry point the shared host's
// systemd unit runs (node /srv/$app/current/index.js). It starts Next's standalone server for $app.
'use strict';
const path = require('path');

const appDir = path.join(__dirname, '$app');

// Caddy on the same host is the only client, so listen on loopback only. PORT comes from the
// systemd unit.
process.env.HOSTNAME = process.env.BIND_HOSTNAME || '127.0.0.1';
// Longer than Caddy's idle upstream keep-alive (2 min), so Node never closes a pooled connection
// Caddy is about to reuse — which surfaces as a sporadic 502.
process.env.KEEP_ALIVE_TIMEOUT = process.env.KEEP_ALIVE_TIMEOUT || '125000';

process.chdir(appDir);
require(path.join(appDir, 'server.js'));
INDEX

echo "Built $(du -sh "$out" | cut -f1) in deployments/shared-host-apps/dist/$app"
